CREATE TABLE IF NOT EXISTS places (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    district VARCHAR(100) NOT NULL,
    neighborhood VARCHAR(100) NOT NULL,
    category VARCHAR(50) NOT NULL,
    overall_score NUMERIC(3, 1) NOT NULL
        CHECK (overall_score BETWEEN 0 AND 10),
    price_level VARCHAR(10) NOT NULL,
    coffee_beans VARCHAR(150),
    ai_summary TEXT NOT NULL,
    taste_score NUMERIC(3, 1) NOT NULL
        CHECK (taste_score BETWEEN 0 AND 10),
    atmosphere_score NUMERIC(3, 1) NOT NULL
        CHECK (atmosphere_score BETWEEN 0 AND 10),
    service_score NUMERIC(3, 1) NOT NULL
        CHECK (service_score BETWEEN 0 AND 10),
    staff_score NUMERIC(3, 1) NOT NULL
        CHECK (staff_score BETWEEN 0 AND 10),
    value_score NUMERIC(3, 1) NOT NULL
        CHECK (value_score BETWEEN 0 AND 10),
    decoration_score NUMERIC(3, 1) NOT NULL
        CHECK (decoration_score BETWEEN 0 AND 10)
);
